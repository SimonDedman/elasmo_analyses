#!/usr/bin/env python3
"""Retract schema-extraction results for papers whose extraction ran over the
WRONG PDF's text (misfiled-PDF blast radius, see
outputs/misfile_blast_radius_2026-09-14/SUMMARY.md).

DRY-RUN BY DEFAULT. Nothing is written unless --apply, --apply-rag, or
--restore is passed explicitly.

Why this exists: extract_schema_columns.py reads a paper's own PDF text and
nothing else (comment "Only use PDF text", ~line 2027 of that script). For
the 85 literature_ids in the blast-radius set, the PDF matched at build time
was a *different paper*, so every column that script wrote for those ids
(all eco_/pr_/gear_/imp_/d_/b_/sb_ binary columns, the eco_*_guess /
depth_* / gear_target_species / imp_* / study_type* text columns) measures
the wrong paper's text. A 0 in one of those columns is not evidence of
absence for the paper the row is nominally about, any more than a 1 is
evidence of presence; both were measured against the wrong text.

What this script does (--apply):
  - nulls those columns for the target literature_ids/rows
  - sets extraction_status = 'retracted_wrong_pdf' (a new provenance column;
    the parquet has no existing extraction-status-like column to reuse: see
    the "provenance columns" section below), plus extraction_retracted_at
    and extraction_retracted_reason
  - leaves every other row's extraction_status untouched (null), so
    never-extracted / successfully-extracted rows stay indistinguishable
    from each other on this field alone (as before), but retracted rows are
    now distinguishable from both.

Target parquet: outputs/literature_review_enriched.parquet is the ONLY
parquet in this repo that carries the extraction columns as a base/source of
truth. outputs/literature_review.parquet (the pre-extraction base, 10 cols)
does not carry them. Two further files copy the columns but are *generated*
from the enriched parquet by their own scripts (outputs/viz_data.csv via
scripts/rebuild_viz_data.py; outputs/rag/paper_filters.parquet via
scripts/rag/build_filters.py) — this tool treats those as derived caches to
be regenerated, not separate targets to hand-patch, to avoid the drift
documented in ~/.claude/.../memory/feedback_corpus_figures_sync.md. Dry-run
reports their presence and current values so you know they need a rebuild
after --apply; it does not touch them. Pass --targets explicitly to add a
file as a direct write target instead.

outputs/meeting_review/enriched_schema_for_plots.csv ALSO copies these
columns and is read by visualize_issue2_schema_plots.R and
visualize_cross_schema_extra.R, but (checked 2026-09-14) NO script in this
repo writes that filename — its mtime is 2026-03-15, six months stale, and
scripts/build_meeting_review_outputs.py (the plausibly-named candidate)
writes different files entirely (missing_papers_*_summary.csv). Dry-run
still reports it (with a warning, not a regen command) so you know those two
R scripts are reading a stale, now-partly-contaminated-then-retracted file
with no known way to refresh it short of finding/rewriting its generator.

Usage:
    # dry run (default) against the blast-radius list
    python3 scripts/retract_wrong_pdf_extractions.py

    # after reviewing the dry run, apply with the exact counts it reported
    python3 scripts/retract_wrong_pdf_extractions.py --apply \\
        --expected-ids 85 --expected-rows 101

    # RAG index: dry-run chunk counts, then remove
    python3 scripts/retract_wrong_pdf_extractions.py --rag
    python3 scripts/retract_wrong_pdf_extractions.py --apply-rag \\
        --expected-ids 85

    # undo
    python3 scripts/retract_wrong_pdf_extractions.py \\
        --restore outputs/retractions/<run_id>/snapshot.json
"""

