def restore_run(snapshot_path: Path) -> None:
    snapshot = json.loads(snapshot_path.read_text())
    for target in snapshot["targets"]:
        path = PROJECT_ROOT / target["path"]
        if not path.exists():
            print(f"SKIP (missing): {path}")
            continue
        df = read_target(path)
        mismatches = []
        for row in target["rows"]:
            idx = row["row_index"]
            if idx not in df.index:
                mismatches.append((idx, "row_index no longer present"))
                continue
            current_id = _norm_id(df.at[idx, "literature_id"])
            if current_id != row["literature_id"]:
                mismatches.append((idx, f"literature_id now {current_id!r}, "
                                          f"expected {row['literature_id']!r}"))
        if mismatches:
            raise SystemExit(
                f"REFUSING to restore {path}: {len(mismatches)} row(s) shifted "
                f"since the snapshot was taken (file structure changed). "
                f"First mismatch: {mismatches[0]}"
            )

        for row in target["rows"]:
            idx = row["row_index"]
            for col, val in row["old_values"].items():
                if col not in df.columns:
                    df[col] = None
                df.at[idx, col] = val

        if path.suffix == ".parquet":
            atomic_write_parquet(df, path)
        else:
            fd, tmp = tempfile.mkstemp(dir=str(path.parent), suffix=".tmp.csv")
            os.close(fd)
            df.to_csv(tmp, index=False)
            os.replace(tmp, path)
        print(f"Restored {len(target['rows'])} rows in {_rel(path)}")


