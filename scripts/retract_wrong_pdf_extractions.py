@dataclass
class TargetReport:
    path: Path
    exists: bool
    n_ids_matched: int = 0
    n_rows_matched: int = 0
    ids_not_found: list[str] | None = None
    dup_id_rows: dict[str, int] | None = None
    nonnull_counts: dict[str, int] | None = None
    status_counts: dict[str, int] | None = None


def read_target(path: Path) -> pd.DataFrame:
    if path.suffix == ".parquet":
        return pd.read_parquet(path)
    return pd.read_csv(path, dtype=str, low_memory=False)


def inspect_target(path: Path, ids: list[str], columns: list[str]) -> tuple[TargetReport, pd.DataFrame | None]:
    if not path.exists():
        return TargetReport(path=path, exists=False), None

    df = read_target(path)
    if "literature_id" not in df.columns:
        return TargetReport(path=path, exists=True), df

    mask = row_mask(df, ids)
    matched = df.loc[mask]
    matched_ids = set(matched["literature_id"].map(_norm_id))
    ids_not_found = sorted(set(ids) - matched_ids)
    dup_counts = matched["literature_id"].map(_norm_id).value_counts()
    dup_id_rows = {k: int(v) for k, v in dup_counts.items() if v > 1}

    present_cols = [c for c in columns if c in df.columns]
    nonnull_counts: dict[str, int] = {}
    for c in present_cols:
        col = matched[c]
        if pd.api.types.is_numeric_dtype(col) or pd.api.types.is_bool_dtype(col):
            n = int(((col.notna()) & (col != 0) & (col != False)).sum())  # noqa: E712
        else:
            n = int((col.notna() & (col.astype(str).str.strip() != "") & (col.astype(str) != "0") & (col.astype(str) != "not stated") & (col.astype(str).str.lower() != "false")).sum())
        if n:
            nonnull_counts[c] = n

    status_counts = {}
    if "extraction_status" in df.columns:
        vc = matched["extraction_status"].fillna("<null>").value_counts()
        status_counts = {str(k): int(v) for k, v in vc.items()}

    report = TargetReport(
        path=path,
        exists=True,
        n_ids_matched=len(matched_ids),
        n_rows_matched=int(mask.sum()),
        ids_not_found=ids_not_found,
        dup_id_rows=dup_id_rows,
        nonnull_counts=nonnull_counts,
        status_counts=status_counts,
    )
    return report, df


def print_target_report(report: TargetReport, present_cols: list[str], total_cols: int) -> None:
    print(f"\n=== {_rel(report.path)} ===")
    if not report.exists:
        print("  MISSING — skipped")
        return
    print(f"  ids matched:  {report.n_ids_matched}")
    print(f"  rows matched: {report.n_rows_matched}")
    if report.dup_id_rows:
        print(f"  ids with >1 row: {len(report.dup_id_rows)} "
              f"(e.g. {list(report.dup_id_rows.items())[:5]})")
    if report.ids_not_found:
        print(f"  IDS NOT FOUND IN THIS FILE ({len(report.ids_not_found)}): "
              f"{report.ids_not_found[:20]}"
              f"{' ...' if len(report.ids_not_found) > 20 else ''}")
    print(f"  target columns present in file: {len(present_cols)}/{total_cols}")
    if report.status_counts:
        print(f"  current extraction_status among matched rows: {report.status_counts}")
    if report.nonnull_counts:
        n_cells = sum(report.nonnull_counts.values())
        print(f"  columns with >=1 currently non-null/non-zero value among "
              f"matched rows: {len(report.nonnull_counts)} "
              f"({n_cells} cells total)")
        top = sorted(report.nonnull_counts.items(), key=lambda kv: -kv[1])[:25]
        for col, n in top:
            print(f"    {col:32s} {n:>4d}")
        if len(report.nonnull_counts) > 25:
            print(f"    ... and {len(report.nonnull_counts) - 25} more columns")
    else:
        print("  (no currently non-null/non-zero values among matched rows "
              "— nothing would visibly change)")


def dry_run(args: argparse.Namespace, ids: list[str], columns: list[str]) -> None:
    print(f"Loaded {len(ids)} distinct literature_ids from {args.ids_csv}")
    print(f"Reason: {args.reason}")
    print(f"\nTarget columns ({len(columns)} total = "
          f"{len(get_binary_columns())} binary schema cols + "
          f"{len(EXTRA_COLUMNS)} extra text/derived cols):")
    for c in columns:
        print(f"  {c}")

    reports = []
    for target_path in args.targets:
        report, _ = inspect_target(target_path, ids, columns)
        present_cols = []
        if report.exists:
            df = read_target(target_path)
            present_cols = [c for c in columns if c in df.columns]
        print_target_report(report, present_cols, len(columns))
        reports.append(report)

    primary = reports[0]
    print("\n=== Derived exports (reported only — regenerate, don't hand-patch) ===")
    for path, cmd in DERIVED_EXPORTS:
        if path in args.targets:
            continue
        if not path.exists():
            print(f"  {_rel(path)}: not present, skip")
            continue
        rep, _ = inspect_target(path, ids, columns)
        n = rep.n_rows_matched if rep.exists else 0
        if cmd:
            print(f"  {_rel(path)}: {n} rows carry these ids "
                  f"— after --apply, regenerate with: {cmd}")
        else:
            age_days = (time.time() - path.stat().st_mtime) / 86400
            print(f"  {_rel(path)}: {n} rows carry these ids "
                  f"— STALE ({age_days:.0f} days old), NO KNOWN GENERATOR "
                  f"script in this repo. Whatever reads this file "
                  f"(visualize_issue2_schema_plots.R, "
                  f"visualize_cross_schema_extra.R) is already working off "
                  f"stale, uncorrected data; --apply does not make that "
                  f"worse, but does not fix it either.")

    print("\n=== For --apply, pass exactly what was found above ===")
    print(f"  --expected-ids {primary.n_ids_matched} "
          f"--expected-rows {primary.n_rows_matched}")

    rag_dry_run(ids, quiet_header=False)


