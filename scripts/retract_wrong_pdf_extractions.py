def load_ids(csv_path: Path, id_column: str) -> list[str]:
    df = pd.read_csv(csv_path, dtype=str)
    if id_column not in df.columns:
        raise SystemExit(
            f"Column {id_column!r} not found in {csv_path}. "
            f"Available columns: {list(df.columns)}"
        )
    ids = df[id_column].dropna()
    ids = ids[ids.str.strip() != ""]
    # normalise "12345.0" -> "12345", strip whitespace
    normed = sorted({_norm_id(v) for v in ids})
    return normed


def _norm_id(v: Any) -> str:
    s = str(v).strip()
    if s.endswith(".0") and s[:-2].isdigit():
        s = s[:-2]
    return s


def row_mask(df: pd.DataFrame, ids: list[str], id_col: str = "literature_id") -> pd.Series:
    normed = df[id_col].map(_norm_id)
    return normed.isin(set(ids))


# ---------------------------------------------------------------------------
# Timestamped backups + atomic writes
# ---------------------------------------------------------------------------

def _run_id() -> str:
    return datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")


def backup_file(path: Path, dest_dir: Path) -> Path:
    dest_dir.mkdir(parents=True, exist_ok=True)
    dest = dest_dir / path.name
    shutil.copy2(path, dest)
    return dest


def atomic_write_parquet(df: pd.DataFrame, path: Path) -> None:
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), suffix=".tmp.parquet")
    os.close(fd)
    try:
        df.to_parquet(tmp, index=False)
        os.replace(tmp, path)
    except Exception:
        Path(tmp).unlink(missing_ok=True)
        raise


def atomic_write_bytes(data: bytes, path: Path) -> None:
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
        os.replace(tmp, path)
    except Exception:
        Path(tmp).unlink(missing_ok=True)
        raise


def atomic_write_text(text: str, path: Path) -> None:
    atomic_write_bytes(text.encode("utf-8"), path)


