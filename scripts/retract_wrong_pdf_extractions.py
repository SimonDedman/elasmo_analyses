def apply_run(args: argparse.Namespace, ids: list[str], columns: list[str]) -> None:
    if args.expected_ids is None or args.expected_rows is None:
        raise SystemExit(
            "--apply requires --expected-ids N --expected-rows N "
            "(run a dry run first and copy the numbers it prints under "
            "'For --apply, pass exactly what was found above')."
        )

    run_id = _run_id()
    run_dir = RETRACTIONS_DIR / run_id
    run_dir.mkdir(parents=True, exist_ok=True)
    backups_dir = run_dir / "backups"

    snapshot: dict[str, Any] = {
        "run_id": run_id,
        "created_at": datetime.now(timezone.utc).isoformat(),
        "ids_csv": str(args.ids_csv),
        "id_column": args.id_column,
        "reason": args.reason,
        "n_ids": len(ids),
        "columns": columns,
        "targets": [],
    }

    now_iso = datetime.now(timezone.utc).isoformat()

    for target_path in args.targets:
        if not target_path.exists():
            raise SystemExit(f"Target does not exist: {target_path}")

        df = read_target(target_path)
        if "literature_id" not in df.columns:
            raise SystemExit(f"{target_path} has no literature_id column — cannot target it")

        mask = row_mask(df, ids)
        matched_idx = df.index[mask]
        matched_ids_found = set(df.loc[mask, "literature_id"].map(_norm_id))

        n_ids_matched = len(matched_ids_found)
        n_rows_matched = int(mask.sum())

        if target_path == args.targets[0]:
            if n_ids_matched != args.expected_ids or n_rows_matched != args.expected_rows:
                raise SystemExit(
                    f"REFUSING: expected {args.expected_ids} ids / "
                    f"{args.expected_rows} rows but found {n_ids_matched} ids / "
                    f"{n_rows_matched} rows matched in {target_path}. "
                    "Re-run the dry run and check nothing changed "
                    "(new sync, new extraction run, wrong CSV) before retrying."
                )

        present_cols = [c for c in columns if c in df.columns]
        for c in PROVENANCE_COLS:
            if c not in df.columns:
                df[c] = None

        # Snapshot BEFORE mutating, one row per matched dataframe row.
        target_rows_snapshot = []
        for idx in matched_idx:
            row = df.loc[idx]
            old_values = {c: _to_jsonable(row[c]) for c in present_cols}
            for c in PROVENANCE_COLS:
                old_values[c] = _to_jsonable(row[c])
            target_rows_snapshot.append({
                "row_index": int(idx),
                "literature_id": _norm_id(row["literature_id"]),
                "old_values": old_values,
            })

        backup_path = backup_file(target_path, backups_dir)

        # Null the extraction columns for matched rows. bool-dtype columns
        # (e.g. imp_quantified) can't hold NaN in place without pandas
        # upcasting; do that explicitly (object dtype) rather than let it
        # warn/eventually error. int/float columns upcast to float64 fine.
        for c in present_cols:
            if pd.api.types.is_bool_dtype(df[c]):
                df[c] = df[c].astype(object)
            df.loc[matched_idx, c] = None

        # Provenance: don't clobber an already-retracted row's timestamp/reason
        # (idempotency) — only set them where extraction_status isn't already
        # RETRACTED_STATUS.
        already_retracted = df.loc[matched_idx, "extraction_status"] == RETRACTED_STATUS
        fresh_idx = matched_idx[~already_retracted.values]
        if len(fresh_idx):
            df.loc[fresh_idx, "extraction_status"] = RETRACTED_STATUS
            df.loc[fresh_idx, "extraction_retracted_at"] = now_iso
            df.loc[fresh_idx, "extraction_retracted_reason"] = args.reason

        if target_path.suffix == ".parquet":
            atomic_write_parquet(df, target_path)
        else:
            fd, tmp = tempfile.mkstemp(dir=str(target_path.parent), suffix=".tmp.csv")
            os.close(fd)
            df.to_csv(tmp, index=False)
            os.replace(tmp, target_path)

        n_fresh = len(fresh_idx)
        n_already = len(matched_idx) - n_fresh
        print(f"{_rel(target_path)}: nulled {len(present_cols)} "
              f"columns x {n_rows_matched} rows ({n_fresh} newly retracted, "
              f"{n_already} already retracted — idempotent no-op). "
              f"Backup: {_rel(backup_path)}")

        snapshot["targets"].append({
            "path": str(_rel(target_path)),
            "backup_path": str(_rel(backup_path)),
            "columns_nulled": present_cols,
            "rows": target_rows_snapshot,
        })

    snapshot_path = run_dir / "snapshot.json"
    atomic_write_text(json.dumps(snapshot, indent=2, ensure_ascii=False), snapshot_path)
    print(f"\nSnapshot written: {_rel(snapshot_path)}")
    print(f"Restore with: python3 scripts/retract_wrong_pdf_extractions.py "
          f"--restore {_rel(snapshot_path)}")
    print("\nDerived exports now stale — regenerate:")
    for path, cmd in DERIVED_EXPORTS:
        if not path.exists():
            continue
        if cmd:
            print(f"  {cmd}")
        else:
            print(f"  {_rel(path)}: no known generator — see dry-run output")


