def _rel(path: Path) -> Path:
    """path relative to PROJECT_ROOT for display, or the path itself if it
    lives outside the project (e.g. a test's tmp_path target)."""
    try:
        return path.relative_to(PROJECT_ROOT)
    except ValueError:
        return path


def _to_jsonable(v: Any) -> Any:
    if v is None:
        return None
    try:
        if pd.isna(v):
            return None
    except (TypeError, ValueError):
        pass
    if isinstance(v, (np.integer,)):
        return int(v)
    if isinstance(v, (np.floating,)):
        return float(v)
    if isinstance(v, (np.bool_,)):
        return bool(v)
    if isinstance(v, (int, float, bool, str)):
        return v
    return str(v)


