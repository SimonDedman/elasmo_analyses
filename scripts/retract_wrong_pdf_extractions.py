def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ids-csv", type=Path, default=DEFAULT_IDS_CSV)
    ap.add_argument("--id-column", default=DEFAULT_ID_COLUMN)
    ap.add_argument("--reason", default=DEFAULT_REASON)
    ap.add_argument("--targets", type=Path, nargs="+", default=[ENRICHED_PARQUET],
                     help="Files to write on --apply (default: the enriched "
                          "parquet only). Derived exports are reported, not "
                          "written, unless listed here explicitly.")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--expected-ids", type=int, default=None)
    ap.add_argument("--expected-rows", type=int, default=None)
    ap.add_argument("--restore", type=Path, default=None, metavar="SNAPSHOT_JSON")
    ap.add_argument("--rag", action="store_true", help="dry-run the RAG chunk count only")
    ap.add_argument("--apply-rag", action="store_true")
    args = ap.parse_args()

    if args.restore:
        restore_run(args.restore)
        return 0

    ids = load_ids(args.ids_csv, args.id_column)
    columns = get_target_columns()

    if args.apply_rag:
        rag_apply(ids, args.expected_ids)
        return 0

    if args.rag:
        rag_dry_run(ids)
        return 0

    if args.apply:
        apply_run(args, ids, columns)
        return 0

    dry_run(args, ids, columns)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
