def _rag_paths() -> dict[str, Path]:
    rag_dir = PROJECT_ROOT / "outputs/rag"
    return {
        "chunks": rag_dir / "chunks_meta.jsonl",
        "embeddings": rag_dir / "embeddings.npy",
        "index": rag_dir / "index.faiss",
        "attempt_log": rag_dir / "pdf_attempt_log.csv",
    }


def rag_dry_run(ids: list[str], quiet_header: bool = True) -> dict[str, int]:
    paths = _rag_paths()
    if not paths["chunks"].exists():
        print("\n=== RAG index ===\n  chunks_meta.jsonl missing — skipping")
        return {}

    id_set = set(ids)
    counts: dict[str, int] = {}
    total = 0
    with open(paths["chunks"], encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            d = json.loads(line)
            lid = _norm_id(d.get("literature_id"))
            if lid in id_set:
                counts[lid] = counts.get(lid, 0) + 1
                total += 1

    print("\n=== RAG index (outputs/rag/) ===")
    print(f"  ids with >=1 chunk: {len(counts)}/{len(ids)}")
    print(f"  total chunks that would be removed: {total}")
    for lid in sorted(counts, key=lambda x: -counts[x])[:15]:
        print(f"    {lid:>10s}  {counts[lid]:>4d} chunks")
    if len(counts) > 15:
        print(f"    ... and {len(counts) - 15} more ids")
    print(f"  For --apply-rag: --expected-ids {len(counts)}")
    print("  Removal method: outputs/rag/index.faiss is a flat IndexFlatIP "
          "(no clustering/training, ids are just row position). Surgical "
          "removal is safe here: filter chunks_meta.jsonl + embeddings.npy "
          "in lockstep, then rebuild the flat index from what remains "
          "(cheap: no re-embedding). --apply-rag does exactly that.")
    return counts


def rag_apply(ids: list[str], expected_ids: int | None) -> None:
    paths = _rag_paths()
    if not paths["chunks"].exists():
        raise SystemExit("outputs/rag/chunks_meta.jsonl missing — nothing to remove")

    counts = rag_dry_run(ids)
    if expected_ids is not None and len(counts) != expected_ids:
        raise SystemExit(
            f"REFUSING: expected {expected_ids} ids with chunks, found {len(counts)}."
        )

    # Import BEFORE any write: on 2026-09-14 a run under system python wrote the
    # filtered chunks and embeddings, then died here, leaving index.faiss stale.
    import faiss  # requires the fashion-clip venv

    id_set = set(ids)
    chunks = []
    keep_mask = []
    with open(paths["chunks"], encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            d = json.loads(line)
            lid = _norm_id(d.get("literature_id"))
            keep = lid not in id_set
            chunks.append(d)
            keep_mask.append(keep)
    keep_mask = np.array(keep_mask, dtype=bool)

    embeddings = np.load(paths["embeddings"])
    if len(embeddings) != len(chunks):
        raise SystemExit(
            f"REFUSING: embeddings.npy has {len(embeddings)} rows but "
            f"chunks_meta.jsonl has {len(chunks)} — files are out of sync, "
            "not safe to filter positionally."
        )

    run_id = _run_id()
    run_dir = RETRACTIONS_DIR / run_id / "rag_backups"
    run_dir.mkdir(parents=True, exist_ok=True)
    for name, p in paths.items():
        if p.exists():
            backup_file(p, run_dir)

    n_removed = int((~keep_mask).sum())
    kept_chunks = [c for c, k in zip(chunks, keep_mask) if k]
    kept_embeddings = embeddings[keep_mask]

    tmp_chunks = paths["chunks"].with_suffix(".tmp.jsonl")
    with open(tmp_chunks, "w", encoding="utf-8") as f:
        for c in kept_chunks:
            f.write(json.dumps(c, ensure_ascii=False) + "\n")
    os.replace(tmp_chunks, paths["chunks"])

    tmp_emb = paths["embeddings"].with_suffix(".tmp.npy")
    np.save(tmp_emb, kept_embeddings)
    os.replace(tmp_emb, paths["embeddings"])

    index = faiss.IndexFlatIP(kept_embeddings.shape[1])
    index.add(kept_embeddings)
    tmp_index = str(paths["index"]) + ".tmp"
    faiss.write_index(index, tmp_index)
    os.replace(tmp_index, paths["index"])

    if paths["attempt_log"].exists():
        rows = []
        with open(paths["attempt_log"], newline="", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            fieldnames = reader.fieldnames
            for row in reader:
                if row.get("status") == "indexed" and _norm_id(row.get("literature_id")) in id_set:
                    row["status"] = RETRACTED_STATUS
                rows.append(row)
        tmp_log = paths["attempt_log"].with_suffix(".tmp.csv")
        with open(tmp_log, "w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=fieldnames)
            w.writeheader()
            w.writerows(rows)
        os.replace(tmp_log, paths["attempt_log"])

    print(f"\nRemoved {n_removed} chunks for {len(counts)} ids. "
          f"Index now covers {len({c['literature_id'] for c in kept_chunks})} "
          f"papers / {len(kept_chunks)} chunks.")
    print(f"Backups: {_rel(run_dir)}")


